"""Stable advertising-domain vocabulary and errors.

PURPOSE: define framework-independent lifecycle, policy, and error codes.
RESPONSIBILITY: own stable machine-readable terms; no persistence or HTTP behavior.
DEPENDENCIES: Python standard library only.
USED BY: advertising entities, policies, services, and adapters.
TESTED BY: tests/unit/domain/test_campaign_states.py and test_policies.py.
"""

from enum import StrEnum


class CampaignState(StrEnum):
    DRAFT = "DRAFT"
    VALIDATED = "VALIDATED"
    PENDING_APPROVAL = "PENDING_APPROVAL"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    EXECUTING = "EXECUTING"
    PUBLISHED = "PUBLISHED"
    FAILED = "FAILED"
    RECONCILIATION_REQUIRED = "RECONCILIATION_REQUIRED"


class CampaignTrigger(StrEnum):
    VALIDATE = "VALIDATE"
    REQUEST_APPROVAL = "REQUEST_APPROVAL"
    APPROVE = "APPROVE"
    REJECT = "REJECT"
    START_EXECUTION = "START_EXECUTION"
    CONFIRM_PUBLISHED = "CONFIRM_PUBLISHED"
    MARK_FAILED = "MARK_FAILED"
    REQUIRE_RECONCILIATION = "REQUIRE_RECONCILIATION"
    RECONCILE_PUBLISHED = "RECONCILE_PUBLISHED"
    RECONCILE_FAILED = "RECONCILE_FAILED"


class ApprovalStatus(StrEnum):
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    CONSUMED = "CONSUMED"


class CampaignObjective(StrEnum):
    SALES = "SALES"
    TRAFFIC = "TRAFFIC"
    LEADS = "LEADS"


class CallToAction(StrEnum):
    SHOP_NOW = "SHOP_NOW"
    LEARN_MORE = "LEARN_MORE"
    CONTACT_US = "CONTACT_US"


class PolicyReasonCode(StrEnum):
    ELIGIBLE = "ELIGIBLE"
    INSUFFICIENT_STOCK = "INSUFFICIENT_STOCK"
    GROSS_MARGIN_BELOW_MINIMUM = "GROSS_MARGIN_BELOW_MINIMUM"
    CANCELLATION_RATE_EXCEEDS_MAXIMUM = "CANCELLATION_RATE_EXCEEDS_MAXIMUM"
    RETURN_RATE_EXCEEDS_MAXIMUM = "RETURN_RATE_EXCEEDS_MAXIMUM"
    INSUFFICIENT_DATA = "INSUFFICIENT_DATA"
    DAILY_BUDGET_BELOW_MINIMUM = "DAILY_BUDGET_BELOW_MINIMUM"
    DAILY_BUDGET_ABOVE_MAXIMUM = "DAILY_BUDGET_ABOVE_MAXIMUM"
    SELLER_DAILY_BUDGET_CEILING_EXCEEDED = "SELLER_DAILY_BUDGET_CEILING_EXCEEDED"
    CURRENCY_MISMATCH = "CURRENCY_MISMATCH"
    STOCK_EMPTY_FOR_PUBLISH = "STOCK_EMPTY_FOR_PUBLISH"
    OBJECTIVE_CTA_NOT_ALLOWED = "OBJECTIVE_CTA_NOT_ALLOWED"
    APPROVAL_NOT_GRANTED = "APPROVAL_NOT_GRANTED"
    APPROVAL_EXPIRED = "APPROVAL_EXPIRED"
    APPROVAL_PAYLOAD_MISMATCH = "APPROVAL_PAYLOAD_MISMATCH"
    APPROVAL_SCOPE_MISMATCH = "APPROVAL_SCOPE_MISMATCH"


class DomainErrorCode(StrEnum):
    INVALID_STATE_TRANSITION = "INVALID_STATE_TRANSITION"
    INVALID_VALUE_OBJECT = "INVALID_VALUE_OBJECT"
    INVALID_POLICY_CONFIGURATION = "INVALID_POLICY_CONFIGURATION"
    OWNERSHIP_VIOLATION = "OWNERSHIP_VIOLATION"
    INVALID_APPROVAL = "INVALID_APPROVAL"


class DomainError(ValueError):
    """Stable, safe domain failure; adapters translate it to application errors."""

    def __init__(self, code: DomainErrorCode, message: str) -> None:
        self.code = code
        super().__init__(message)
